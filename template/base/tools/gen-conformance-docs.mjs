#!/usr/bin/env node
// Generator: the two enterprise-facing documents DERIVED from the conformance map — the
// controls crosswalk (which control bears on which requirement, per standard) and the
// threat model (what the agent-time guards refuse, what the map leaves uncovered, and the
// limits the covered rows state about themselves). Committed, regen-diffed artefacts: the
// `docs-sync` step's third script (tools/check-conformance-map.mjs) runs this in --check
// mode, so a hand-edit to either document reds as drift.
//
//   node tools/gen-conformance-docs.mjs           # write both documents
//   node tools/gen-conformance-docs.mjs --check   # regen-diff (exit 1 naming the drifted file)
//
// THREE MACHINE-READ INPUTS and nothing typed: tools/conformance-map.json (the rows and
// their grades), tools/harness.config.mjs (the chain, so every step is placed — mapped or
// unmapped-with-reason), and .claude/hooks/lib/guard-rules.mjs (the rule tables the hooks
// run, imported as the pure data they are). The output is DETERMINISTIC by construction:
// register order for rows, chain order for steps, table order for rules, no dates other
// than the register's own verifiedOn — a fresh generation on any machine is byte-identical.
//
// WHAT THESE DOCUMENTS DO NOT SAY, and the generator writes the sentence into both so no
// later edit can drop it: a mapping is not a verification. A level attaches to a
// verification of an application performed by an assessor; CRA conformity is a
// manufacturer's legal act; and no harmonised standard for the CRA had been cited in the
// Official Journal as of the register's verified date, so the CRA rows carry a shelf life.
// SOURCE: tools/lib/conformance-map.mjs (the register machinery these documents derive from)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import process from 'node:process'
import { pathToFileURL } from 'node:url'
import { STOP_HOOK_STEPS, VALIDATE_STEPS } from './harness.config.mjs'
import { guardRuleIds, summarise } from './lib/conformance-map.mjs'

const ROOT = process.cwd()
const REGISTER = 'tools/conformance-map.json'
const GUARD_RULES = '.claude/hooks/lib/guard-rules.mjs'
const CROSSWALK = 'docs/compliance/controls-crosswalk.md'
const THREAT_MODEL = 'docs/security/threat-model.md'
const SELF = 'tools/gen-conformance-docs.mjs'

const STANDARD_LABEL = { asvs: 'ASVS 5.0.0', masvs: 'MASVS 2.1', cra: 'CRA Annex I' }
const STANDARDS = ['asvs', 'masvs', 'cra']

// --- inputs -------------------------------------------------------------------------------
const die = (msg) => {
  process.stderr.write(`${msg}\n`)
  process.exit(1)
}
if (!existsSync(join(ROOT, REGISTER))) die(`${REGISTER} not found — nothing to generate from.`)
let register
try {
  register = JSON.parse(readFileSync(join(ROOT, REGISTER), 'utf8'))
} catch (e) {
  die(`${REGISTER} is not valid JSON: ${e instanceof Error ? e.message : String(e)}`)
}
const rows = Array.isArray(register.requirements) ? register.requirements : []
if (rows.length === 0)
  die(`${REGISTER} declares no requirements — refusing to generate documents from an empty map.`)

const guardPath = join(ROOT, GUARD_RULES)
if (!existsSync(guardPath))
  die(`${GUARD_RULES} not found — the threat model derives from the rule tables.`)
const guardSource = readFileSync(guardPath, 'utf8')
const guardOwner = guardRuleIds(guardSource)
/** The rule tables as data, in source order — pure exports, so an import is honest. */
const guardModule = await import(pathToFileURL(guardPath).href)
const RULE_TABLES = [...guardSource.matchAll(/^export const ([A-Z_]+) = \[/gm)]
  .map((m) => m[1])
  .filter(
    (name) =>
      Array.isArray(guardModule[name]) && guardModule[name].some((r) => typeof r?.id === 'string'),
  )

const steps = [...VALIDATE_STEPS, ...STOP_HOOK_STEPS].map(([name]) => name)
const stepSet = new Set(steps)
const summary = summarise(register)
const cra = register.source?.cra ?? {}
const verifiedOn = String(cra.verifiedOn ?? 'the register’s verifiedOn')

// --- shared prose -------------------------------------------------------------------------
const GENERATED_BANNER = (what) =>
  `<!-- GENERATED by ${SELF} from ${REGISTER} — DO NOT EDIT. The docs-sync gate regen-diffs this file; change the register and regenerate. -->\n\n> **Generated document.** ${what} Every figure below is derived from \`${REGISTER}\` by \`${SELF}\`; a hand edit here is a claim nobody reviewed and reds the \`docs-sync\` step.`

const HONEST_LIMITS = [
  '## What this document does not claim',
  '',
  '**A mapping is not a verification, and this document claims no level.** A verification level attaches to a verification *of an application* performed by an assessor against that application; a template cannot hold one and a generator cannot confer one. This map states which live control in the tree bears on each requirement, how much of it that control reaches, and what is left — so an assessor starts from an honest ledger and a consumer never mistakes a template for a verification. It never says the generated application is ASVS Level 1, 2 or 3, MASVS-verified, or CRA-conformant, and `tools/check-conformance-map.mjs` reds any sentence in the register that does.',
  '',
  `**The CRA rows carry a shelf life.** CRA conformity is a manufacturer’s legal act — Annex I obligations, a conformity assessment, a declaration, CE marking — that no code tree performs, and no harmonised standard for the CRA had been cited in the Official Journal as of ${verifiedOn} — the register records: “${String(cra.harmonisedStandards ?? 'see the register header')}”. The Annex I rows are mapped against the regulation’s text directly and must be re-read when a harmonised standard is cited.`,
  '',
  `**Module rows are conditional.** ${String(summary.moduleConditional)} row(s) rest on an opt-in module (\`module\` set in the register) and are graded on the assumption that the module is enabled; on a tree without it the row is CONDITIONAL, judged for liveness only where the module’s \`docs/modules/<name>/README.md\` marker exists, and its control may not run here at all.`,
  '',
  `**Organisation-boundary rows are enumerated, never graded up.** ${String(summary.byBoundary.organisation)} row(s) name something only the operating organisation can meet (policies, processes, notifications, contracts); the register may not grade them \`covered\` or \`partial\`, and this document lists them so nobody mistakes the tree’s silence for the operator’s compliance.`,
  '',
  '**Grades are conservative by rule.** Absence of a surface is never coverage; where two grades are defensible the lower is taken; `covered` may not rest on documentation alone; and `not-covered` is not a failure the gate reds on — it is the honest statement of what would be needed.',
].join('\n')

const partitionSentence = `${String(summary.total)} mapped requirements: ${String(summary.covered)} covered, ${String(summary.partial)} partial, ${String(summary.notCovered)} not-covered, ${String(summary.notApplicable)} not-applicable — ASVS 5.0.0 (${String(summary.byStandard.asvs)}), MASVS 2.1 (${String(summary.byStandard.masvs)}), CRA Annex I (${String(summary.byStandard.cra)}).`

// --- helpers ------------------------------------------------------------------------------
/** The first sentence of a requirement text — enough to recognise it, short enough to list. */
const firstSentence = (text) => {
  const t = String(text ?? '')
    .replace(/\s+/g, ' ')
    .trim()
  const m = /^(.*?[.;])(?:\s|$)/.exec(t)
  return m ? m[1] : t
}
/** `- ASVS 5.0.0: 8.2.2 (covered), 8.3.1 (covered)` lines for a set of rows, per standard. */
const perStandard = (list) =>
  STANDARDS.flatMap((std) => {
    const mine = list.filter((r) => r.standard === std)
    return mine.length === 0
      ? []
      : [`- ${STANDARD_LABEL[std]}: ${mine.map((r) => `${r.id} (${r.outcome})`).join(', ')}`]
  })
/** Rows naming a control, keyed by control, in register order. */
const byControl = new Map()
for (const r of rows) {
  if (!r.control) continue
  if (!byControl.has(r.control)) byControl.set(r.control, [])
  byControl.get(r.control).push(r)
}
/** Which section a control belongs to. Chain steps first (two names — db-limits, data-flow
 * — are both a step and a guard-rule id; the step is the control a row means, and the
 * rule protects the step's policy file). */
const controlKind = (c) => (stepSet.has(c) ? 'step' : guardOwner.has(c) ? 'guard' : 'lane')

// --- the crosswalk ------------------------------------------------------------------------
function renderCrosswalk() {
  const out = [
    '# Controls crosswalk — ASVS 5.0.0 · MASVS 2.1 · CRA Annex I',
    '',
    GENERATED_BANNER(
      'For each control this tree runs, the requirements it bears on and how far it reaches.',
    ),
    '',
    HONEST_LIMITS,
    '',
    '## Standing',
    '',
    `**${partitionSentence}** The gate prints this exact partition (\`node tools/check-conformance-map.mjs\`) and \`scripts/check-claims.mjs\` holds the README to it, so the published figure and the register cannot drift apart.`,
    '',
    '| Standard | Rows | covered | partial | not-covered | not-applicable |',
    '| --- | ---: | ---: | ---: | ---: | ---: |',
  ]
  for (const std of STANDARDS) {
    const mine = rows.filter((r) => r.standard === std)
    const n = (o) => String(mine.filter((r) => r.outcome === o).length)
    out.push(
      `| ${STANDARD_LABEL[std]} | ${String(mine.length)} | ${n('covered')} | ${n('partial')} | ${n('not-covered')} | ${n('not-applicable')} |`,
    )
  }
  out.push(
    '',
    `ASVS rows by the requirement’s OWN level (never a claimed one): L1 ${String(summary.asvsByLevel[1])}, L2 ${String(summary.asvsByLevel[2])}, L3 ${String(summary.asvsByLevel[3])}. Boundary: harness ${String(summary.byBoundary.harness)}, consumer ${String(summary.byBoundary.consumer)}, shared ${String(summary.byBoundary.shared)}, organisation ${String(summary.byBoundary.organisation)}.`,
    '',
    '## Chain-step controls',
    '',
    'Every step of `VALIDATE_STEPS` and `STOP_HOOK_STEPS` (`tools/harness.config.mjs`), in chain order. A step is either listed here with the requirements it bears on, or listed under *Unmapped chain steps* with the reason no requirement is its subject — never neither, never both (`tools/check-conformance-map.mjs` closes it).',
    '',
  )
  const unmapped = register.unmappedControls ?? {}
  for (const step of steps) {
    if (!byControl.has(step)) continue
    out.push(`### \`${step}\``, '', ...perStandard(byControl.get(step)), '')
  }
  out.push(
    '## Unmapped chain steps',
    '',
    'Steps that run on every validate and are named as no row’s control, each with its recorded reason.',
    '',
  )
  for (const step of steps) {
    if (byControl.has(step)) continue
    out.push(
      `- \`${step}\` — ${String(unmapped[step] ?? 'NO REASON RECORDED (the gate reds this)')}`,
    )
  }
  out.push(
    '',
    '## Workflow-lane controls',
    '',
    'CI jobs (and, for module rows, a module’s own workflow job) named as a control. A lane may be conditional — path-filtered, schedule-gated or event-gated — and the row’s note says which; the crosswalk lists what the lane bears on, not that it ran on a given commit.',
    '',
  )
  for (const [control, list] of byControl) {
    if (controlKind(control) !== 'lane') continue
    out.push(`### \`${control}\``, '', ...perStandard(list), '')
  }
  out.push(
    '## Write-guard rule controls',
    '',
    'Agent-time rules from `.claude/hooks/lib/guard-rules.mjs` named as a control: they refuse the WRITE, before any gate runs, and are live on every Edit/Write/Bash tool call. Their can-fail proofs are registered under the HOOK that runs them (`tests/canary/injections.json` hookRules).',
    '',
  )
  for (const [control, list] of byControl) {
    if (controlKind(control) !== 'guard') continue
    out.push(
      `### \`${control}\` (${String(guardOwner.get(control))})`,
      '',
      ...perStandard(list),
      '',
    )
  }
  out.push(
    '## Module-conditional rows',
    '',
    'Rows that rest on an opt-in module. On a tree without the module the row is CONDITIONAL and its control is not judged for liveness.',
    '',
  )
  for (const r of rows.filter((x) => x.module)) {
    out.push(
      `- ${r.id} (${STANDARD_LABEL[r.standard]}, ${r.outcome}) — module \`${String(r.module)}\`, control \`${String(r.control)}\``,
    )
  }
  out.push(
    '',
    '## Organisation-boundary rows',
    '',
    'Requirements only the operating organisation can meet. Enumerated so the tree’s silence is never read as the operator’s compliance; graded not-covered or not-applicable by rule.',
    '',
  )
  const org = rows.filter((x) => x.boundary === 'organisation')
  out.push(...perStandard(org), '')
  return `${out
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trimEnd()}\n`
}

// --- the threat model ---------------------------------------------------------------------
/** The stated-limit sentence(s) of a covered row, or null when the note carries no marker. */
const LIMIT_MARKER =
  /\b(?:What this does not reach|Residuals? stated(?: plainly)?|Residual|Honest limit|The residual is|What is proven live)\b/
const statedLimit = (note) => {
  const m = LIMIT_MARKER.exec(String(note ?? ''))
  return m ? String(note).slice(m.index).replace(/\s+/g, ' ').trim() : null
}
/** One rule as a bullet: id, what it refuses (message first sentence, or the protected path), and the rows resting on it. */
const ruleBullet = (rule) => {
  const what =
    typeof rule.message === 'string'
      ? firstSentence(rule.message)
      : rule.re instanceof RegExp
        ? `protected path \`${rule.re.source}\``
        : 'refused by predicate'
  const bearing = byControl.get(rule.id)
  const bears = bearing
    ? ` — bears on ${bearing.map((r) => `${r.id} (${r.outcome})`).join(', ')}`
    : ''
  return `- \`${String(rule.id)}\` — ${what}${bears}`
}

function renderThreatModel() {
  const out = [
    '# Threat model — what the enforcement layers refuse, and what they leave',
    '',
    GENERATED_BANNER(
      'What the agent-time guards refuse, which requirements the tree does not reach, and the limits the covered rows state about themselves.',
    ),
    '',
    HONEST_LIMITS,
    '',
    '## How to read this',
    '',
    'Three layers enforce this tree: agent-time hooks (the rule tables below refuse a write or a command at the moment it is attempted), the validate/Stop chains (`docs/harness/gates-catalog.md`), and CI lanes. This document is the hooks’ half plus the map’s negative space: every rule the guards run, grouped by the table that holds it; every requirement the map grades `not-covered`; every module-conditional row; and the residual each `covered` row states in its own words. The positive half — which control bears on which requirement — is `docs/compliance/controls-crosswalk.md`.',
    '',
    '## Agent-time refusals',
    '',
    `Rule tables from \`${GUARD_RULES}\`, in source order. Each rule is denied on the FIRST match; every id has a behavioural canary in the hook-contract suite. A rule that a conformance row rests on says so.`,
    '',
  ]
  for (const table of RULE_TABLES) {
    const owner = new Set(guardModule[table].map((r) => guardOwner.get(r.id)))
    out.push(`### \`${table}\` (${[...owner].join(', ')})`, '')
    for (const rule of guardModule[table]) out.push(ruleBullet(rule))
    out.push('')
  }
  out.push(
    '## Uncovered and residual',
    '',
    `Every row the map grades \`not-covered\` — nothing in the tree bears on it: honestly unbuilt, or the consumer’s to build. ${String(summary.notCovered)} row(s). The register’s note on each says what would be needed.`,
    '',
  )
  for (const std of STANDARDS) {
    const mine = rows.filter((r) => r.standard === std && r.outcome === 'not-covered')
    if (mine.length === 0) continue
    out.push(`### ${STANDARD_LABEL[std]} (${String(mine.length)})`, '')
    for (const r of mine) out.push(`- **${r.id}** — ${firstSentence(r.text)}`)
    out.push('')
  }
  out.push(
    '### Module-conditional rows',
    '',
    'Graded on the assumption the module is enabled; without it, the row is conditional and its control may not run here.',
    '',
  )
  for (const r of rows.filter((x) => x.module)) {
    out.push(
      `- **${r.id}** (${STANDARD_LABEL[r.standard]}, ${r.outcome}, module \`${String(r.module)}\`) — ${firstSentence(r.text)}`,
    )
  }
  out.push(
    '',
    '## Stated limits',
    '',
    'What each `covered` row says it does NOT reach, in the register’s own words — extracted from the note at its residual marker. A covered row without a stated limit is omitted here, not paraphrased.',
    '',
  )
  for (const r of rows.filter((x) => x.outcome === 'covered')) {
    const limit = statedLimit(r.note)
    if (limit)
      out.push(`- **${r.id}** (${STANDARD_LABEL[r.standard]}, \`${String(r.control)}\`) — ${limit}`)
  }
  return `${out
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trimEnd()}\n`
}

// --- write or check -----------------------------------------------------------------------
const outputs = [
  [CROSSWALK, renderCrosswalk()],
  [THREAT_MODEL, renderThreatModel()],
]
if (process.argv.includes('--check')) {
  const drifted = outputs.filter(
    ([file, next]) =>
      (existsSync(join(ROOT, file)) ? readFileSync(join(ROOT, file), 'utf8') : '') !== next,
  )
  if (drifted.length > 0) {
    for (const [file] of drifted) {
      process.stderr.write(
        `${file}: out of date with ${REGISTER} — regenerate with \`node ${SELF}\`\n`,
      )
    }
    process.exit(1)
  }
  process.stdout.write(`${CROSSWALK} + ${THREAT_MODEL}: in sync (${String(rows.length)} row(s))\n`)
} else {
  for (const [file, next] of outputs) {
    mkdirSync(dirname(join(ROOT, file)), { recursive: true })
    writeFileSync(join(ROOT, file), next)
    process.stdout.write(`wrote ${file}\n`)
  }
}
