#!/usr/bin/env node
// Generator: the AGENT-SURFACE lock — sha256 per file over `.claude/{agents,commands,skills}`,
// plus the model each agent is pinned to.
//
// WHAT IT IS FOR. Those three directories are the instructions the coding agent runs
// under: which reviewers exist, what they may touch, what a slash command does, what the
// skills prescribe. They are the most privileged prose in the repository and, before this
// lock, nothing noticed them changing. An agent could soften `security-reviewer.md`,
// widen a skill, or repoint a command, and every gate stayed green — the roster check in
// `docs-sync` reads frontmatter (tools, model, name) and never the body, where the actual
// instructions live.
//
// WHY THIS ONE GENERATOR REFUSES TO WRITE, WHEN THE OTHER THREE DO NOT. It is worth
// stating precisely, because "guard every generator" is the wrong lesson and would only
// add friction. `gen-action-inventory`, `gen-event-catalog` and `gen-query-shapes` derive
// their output from something ELSE the gates check — the composed router, the event
// catalogs, the DAL's own execution. Running them cannot launder anything: the only way
// to change what they emit is to change the artifact the rest of the chain judges.
//
// This generator is the opposite shape. Its output is a HASH OF THE FILES BEING CHECKED,
// so running it after an edit is exactly how you make the edit invisible. `--write` is
// therefore human-in-the-loop (HARNESS_ALLOW_SELF_EDIT=1), the bash-guard denies invoking
// any `gen-*-lock` writer from the shell, and the lock file itself is write-protected.
// Three layers, because one of them being an env var means a single leaked export would
// otherwise be the whole control.
//
//   node tools/gen-agents-lock.mjs            # print the lock that WOULD be written
//   node tools/gen-agents-lock.mjs --check    # exit 1 if the committed lock is stale
//   HARNESS_ALLOW_SELF_EDIT=1 node tools/gen-agents-lock.mjs --write
//
// SOURCE: docs/harness/README.md (prompt/agent lock discipline) [corpus: harness/doctrine]
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import process from 'node:process'
import { parseFrontmatter } from './lib/agent-roster.mjs'
import { AGENT_SURFACE } from './lib/agent-surface.mjs'
import { walkFiles } from './lib/fs-walk.mjs'

export const OUTPUT = 'tools/agents.lock.json'

/**
 * Every file on the agent surface, POSIX-pathed and code-unit sorted (walkFiles sorts),
 * with its sha256. Binary-safe: hashed as bytes, never as decoded text, so a stray CRLF
 * or an image in a skill directory is still covered.
 */
export function lockFiles(roots = AGENT_SURFACE) {
  const files = {}
  for (const root of roots) {
    for (const rel of walkFiles(root)) {
      const path = `${root}/${rel}`
      files[path] = createHash('sha256').update(readFileSync(path)).digest('hex')
    }
  }
  return files
}

/**
 * The model each agent is pinned to, recorded ALONGSIDE the hash rather than instead of
 * it. A hash proves the file did not change; it does not say which model reads it, and a
 * roster silently repointed from a frontier model to a cheap one is a real degradation
 * that leaves every byte of the instructions identical.
 */
export function lockModels(dir = '.claude/agents') {
  const models = {}
  for (const rel of walkFiles(dir, { filter: (p) => p.endsWith('.md') })) {
    const parsed = parseFrontmatter(readFileSync(`${dir}/${rel}`, 'utf8'))
    models[rel.slice(0, -3)] = parsed.ok ? (parsed.data.model?.trim() ?? null) : null
  }
  return models
}

export function renderLock() {
  return `${JSON.stringify(
    {
      comment:
        "GENERATED by tools/gen-agents-lock.mjs — sha256 over .claude/{agents,commands,skills} plus each agent's pinned model. The `prompts` gate holds the surface to it. Never hand-edit: regenerating after an edit is how an edit becomes invisible, which is why --write needs HARNESS_ALLOW_SELF_EDIT=1 and the bash-guard denies running it from the shell.",
      models: lockModels(),
      files: lockFiles(),
    },
    null,
    2,
  )}\n`
}

const next = renderLock()

if (process.argv.includes('--check')) {
  const committed = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : ''
  if (next !== committed) {
    process.stderr.write(`${OUTPUT} is stale — the agent surface changed without a lock update.\n`)
    process.exit(1)
  }
  process.stdout.write(`${OUTPUT}: in sync\n`)
} else if (process.argv.includes('--write')) {
  if (process.env['HARNESS_ALLOW_SELF_EDIT'] !== '1') {
    process.stderr.write(
      `${OUTPUT}: refusing to write. This lock is a hash OF THE FILES IT PROTECTS, so regenerating it after an edit is exactly how the edit becomes invisible. Updating it is a human act: re-run with HARNESS_ALLOW_SELF_EDIT=1, and put the diff in the PR.\n`,
    )
    process.exit(1)
  }
  writeFileSync(OUTPUT, next)
  process.stdout.write(`wrote ${OUTPUT}\n`)
} else {
  // Default is PRINT, not write — see the header. An agent that wants to know what the
  // lock would say can find out; it cannot make it so.
  process.stdout.write(next)
}
