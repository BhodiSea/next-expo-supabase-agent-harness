// The content loader for Starlight's `docs` collection. It reads the corpus IN PLACE.
//
// Why not glob(), or Starlight's docsLoader(), which is glob() with a fixed base:
//   1. glob() validates the data with parseData BEFORE it renders, and the corpus has no
//      frontmatter, so the `title` Starlight requires must exist before the Markdown is
//      parsed. Here the render runs first and the title comes out of it (markdown-plugins.mjs).
//   2. starlight-links-validator keys each page by `frontmatter.slug`, else by the file's
//      path relative to src/content/docs. A file outside that folder matches no route, so
//      every link INTO the page would be reported invalid. The render carries a `slug`.
//   3. Starlight reads git dates only for src/content/docs, so `lastUpdated` is set here.
// Only documented LoaderContext APIs are used: renderMarkdown, parseData, store,
// generateDigest, logger and watcher.
import { spawnSync } from 'node:child_process'
import { existsSync } from 'node:fs'
import { readFile, readdir } from 'node:fs/promises'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { DEFAULT_BRANCH, GITHUB_REPO, REPO_ROOT, loadCorpus, repoRelative } from './corpus.mjs'

const git = (args) =>
  spawnSync('git', args, { cwd: REPO_ROOT, encoding: 'utf8', timeout: 60_000, maxBuffer: 64 * 1024 * 1024 })

/** Newest commit time per repo-relative path, from ONE git call. */
function lastCommitDates(paths, logger) {
  const dates = new Map()
  const res = git(['log', '--format=t:%ct', '--name-only', '--', ...paths])
  if (res.status !== 0) {
    logger.warn(`git log failed (${res.error?.message ?? res.stderr.trim()}); pages ship without "last updated"`)
    return dates
  }
  // A shallow clone has no history to read, so every page would carry the newest commit's date.
  if (git(['rev-parse', '--is-shallow-repository']).stdout.trim() === 'true') {
    logger.warn('shallow clone: "last updated" shows the checkout commit for every page (pages.yml fetches full history)')
  }
  let current
  for (const line of res.stdout.split('\n')) {
    if (line.startsWith('t:')) current = new Date(Number(line.slice(2)) * 1000)
    else if (line && current && !dates.has(line)) dates.set(line, current)
  }
  return dates
}

/** The site's own pages (the landing page), which DO carry frontmatter. */
async function localPages(srcDocsDir) {
  const files = (await readdir(srcDocsDir, { recursive: true }).catch(() => []))
    .map((f) => String(f).split(sep).join('/'))
    .filter((f) => f.endsWith('.md'))
    .sort()
  return files.map((rel) => {
    const absPath = join(srcDocsDir, rel)
    // `index` at the top is the site root (Starlight maps the id "index" to "/").
    const id = rel.replace(/\.md$/, '').replace(/\/index$/, '')
    return { repoPath: repoRelative(absPath), absPath, fileURL: pathToFileURL(absPath), route: id, local: true }
  })
}

/**
 * The edit link: the file itself, or for a page generated from a register
 * (`<!-- GENERATED by <tool> from <register>`), the register, resolved in the page's own tree.
 */
function editUrlFor(page, source) {
  const generated = /<!--\s*GENERATED by \S+ from (\S+)/.exec(source.slice(0, 600))
  if (!generated) return `${GITHUB_REPO}/edit/${DEFAULT_BRANCH}/${page.repoPath}`
  const register = `${page.repoPath.slice(0, page.repoPath.indexOf('/docs/'))}/${generated[1]}`
  if (!existsSync(join(REPO_ROOT, register))) {
    throw new Error(`${page.repoPath}: its GENERATED banner names ${register}, which does not exist`)
  }
  return `${GITHUB_REPO}/edit/${DEFAULT_BRANCH}/${register}`
}

const hasFrontmatter = (source) => (source.charCodeAt(0) === 0xfeff ? source.slice(1) : source).startsWith('---')

/**
 * Render one page and assemble its data before validation. A corpus page gets a synthetic
 * frontmatter block with only `slug`; its title and description come out of the render.
 */
async function renderPage(page, renderMarkdown, dates) {
  const source = await readFile(page.absPath, 'utf8')
  const lastUpdated = dates.get(page.repoPath)
  const dated = (data) => (lastUpdated && data.lastUpdated === undefined ? { ...data, lastUpdated } : data)
  if (page.local) {
    const rendered = await renderMarkdown(source, { fileURL: page.fileURL })
    return { source, input: source, rendered, data: dated(rendered.metadata.frontmatter ?? {}) }
  }
  // The corpus has no frontmatter by contract; fail closed if that ever changes.
  if (hasFrontmatter(source)) throw new Error(`${page.repoPath}: unexpected frontmatter in the corpus`)
  const input = `---\nslug: ${JSON.stringify(page.route)}\n---\n${source}`
  const rendered = await renderMarkdown(input, { fileURL: page.fileURL })
  const { slug: _slug, ...frontmatter } = rendered.metadata.frontmatter ?? {}
  if (typeof frontmatter.title !== 'string' || frontmatter.title === '') {
    throw new Error(`${page.repoPath}: no top-level "# " heading to take the page title from`)
  }
  return { source, input, rendered, data: dated({ ...frontmatter, editUrl: editUrlFor(page, source) }) }
}

export function harnessDocsLoader() {
  return {
    name: 'harness-docs-loader',
    async load({ config, store, parseData, renderMarkdown, generateDigest, logger, watcher }) {
      const root = fileURLToPath(config.root)
      const srcDocsDir = fileURLToPath(new URL('content/docs/', config.srcDir))

      async function sync() {
        const { pages } = loadCorpus()
        const all = [...(await localPages(srcDocsDir)), ...pages]
        const dates = lastCommitDates(['template/base/docs', 'template/modules', repoRelative(srcDocsDir)], logger)
        const seen = new Set()
        for (const page of all) {
          if (seen.has(page.route)) throw new Error(`two pages claim the route "/${page.route}"`)
          seen.add(page.route)
          const { source, input, rendered, data } = await renderPage(page, renderMarkdown, dates)
          store.set({
            id: page.route,
            data: await parseData({ id: page.route, data, filePath: page.absPath }),
            body: source,
            filePath: relative(root, page.absPath).split(sep).join('/'),
            digest: generateDigest(input),
            rendered,
          })
        }
        for (const id of store.keys()) if (!seen.has(id)) store.delete(id)
        logger.info(`loaded ${String(all.length)} page(s) in place (${String(pages.length)} from the repository corpus)`)
      }

      await sync()

      // `astro dev` only: re-render when a corpus file changes. An added or deleted file
      // changes the routes and the sidebar, which are computed when astro.config.mjs
      // loads, so those need a restart of the dev server.
      if (!watcher) return
      const watched = new Set(loadCorpus().pages.map((p) => p.absPath))
      for (const dir of new Set(loadCorpus().pages.map((p) => dirname(p.absPath)))) watcher.add(dir)
      watcher.on('change', async (changed) => {
        if (!watched.has(changed)) return
        logger.info(`re-rendering ${repoRelative(changed)}`)
        await sync()
      })
    },
  }
}
